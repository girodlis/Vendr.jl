# Single scenario: loss V, dense data, regularization weight tuned in 21_gridded_A_reg.

# (loss_type, regularization_weight)
scenarios = [
    ("V", 3e37),
]

out = joinpath(@__DIR__, "scenarios.toml")

open(out, "w") do io
    println(io, "# Auto-generated by scenarios.jl")
    println(io)

    for (sid, (loss_type, reg_weight)) in enumerate(scenarios)
        println(io, "[[scenarios]]")
        println(io, "id = \"S$(sid)\"")
        println(io, "loss_type = \"$(loss_type)\"")
        println(io, "use_tim = false")
        println(io, "sparsity_H = false")
        println(io, "sparsity_V_sigma = 0.0")
        println(io, "sparsity_V_threshold = 0.0")
        println(io, "regularization_weight = $(reg_weight)")
        println(io)
    end
end
