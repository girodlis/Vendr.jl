# Generate config/scenarios.toml
# Dense data for each loss type, then each loss type with only its own data sparsified.

# (loss_type, sparsity_H, sparsity_V_sigma, sparsity_V_threshold)
scenarios = [
    ("H",  false, 0.0, 0.0),
    ("V",  false, 0.0, 0.0),
    ("HV", false, 0.0, 0.0),
    ("V",  false, 0.7, 0.02),
    ("H",  true,  0.0, 0.0),
    ("HV", true,  0.7, 0.02),
]

out = joinpath(@__DIR__, "scenarios.toml")

open(out, "w") do io
    println(io, "# Auto-generated by scenarios.jl")
    println(io)

    for (sid, (loss_type, sparsity_H, sigma, threshold)) in enumerate(scenarios)
        println(io, "[[scenarios]]")
        println(io, "id = \"S$(sid)\"")
        println(io, "loss_type = \"$(loss_type)\"")
        println(io, "use_tim = false")
        println(io, "sparsity_H = $(sparsity_H)")
        println(io, "sparsity_V_sigma = $(sigma)")
        println(io, "sparsity_V_threshold = $(threshold)")
        println(io)
    end
end
