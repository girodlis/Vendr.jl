# Generate config/scenarios.toml (16 scenarios)
# 3 (loss_type) x 2 (use_tim) x 2 (sparsity_H) x 2 (sparsity_V), minus the
# redundant combinations where the sparsified data is not used by the loss:
#   - loss "H" with sparse V
#   - loss "V" with sparse H

loss_types = ["H", "V", "HV"]
use_tim_values = [false, true]
sparsity_H_values = [false, true]

sparsity_V_levels = [
    (0.0, 0.0),   # no sparsity
    (0.7, 0.02),  # (sigma, threshold)
]

is_redundant(loss_type, sparsity_H, sparsity_V) =
    (loss_type == "H" && sparsity_V) || (loss_type == "V" && sparsity_H)

out = joinpath(@__DIR__, "scenarios.toml")

open(out, "w") do io
    println(io, "# Auto-generated by scenarios.jl")
    println(io)

    sid = 1
    for use_tim in use_tim_values
        for sparsity_H in sparsity_H_values
            for (sigma, threshold) in sparsity_V_levels
                for loss_type in loss_types
                    is_redundant(loss_type, sparsity_H, sigma > 0) && continue
                    println(io, "[[scenarios]]")
                    println(io, "id = \"S$(sid)\"")
                    println(io, "loss_type = \"$(loss_type)\"")
                    println(io, "use_tim = $(use_tim)")
                    println(io, "sparsity_H = $(sparsity_H)")
                    println(io, "sparsity_V_sigma = $(sigma)")
                    println(io, "sparsity_V_threshold = $(threshold)")
                    println(io)
                    sid += 1
                end
            end
        end
    end
end
